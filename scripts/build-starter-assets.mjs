import {readFile,writeFile} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import {brotliCompressSync,constants} from 'node:zlib';
import {fileURLToPath} from 'node:url';

const project=new URL('../',import.meta.url);
export async function starterAssetSource(){
  const assets=JSON.parse(await readFile(new URL('examples/covers.json',project),'utf8'));
  const compressed=[];
  for(const asset of assets){
    const bytes=await readFile(new URL(`examples/vault/示例/附件/${asset.cover}`,project));
    if(createHash('sha256').update(bytes).digest('hex')!==asset.sha256)throw new Error(`Original cover fingerprint changed: ${asset.id}`);
    const data=brotliCompressSync(bytes,{params:{[constants.BROTLI_PARAM_QUALITY]:11}}).toString('base64');
    compressed.push({...asset,encoding:'brotli-base64',byteLength:bytes.length,data});
  }
  return '// Generated by scripts/build-starter-assets.mjs from byte-exact originals.\n// Provenance: examples/SOURCES.md; cover assets are not MIT licensed.\n'+
    'export interface StarterAsset { id: string; type: "book" | "film"; title: string; cover: string; sha256: string; encoding: "brotli-base64"; byteLength: number; data: string; }\n'+
    `export const STARTER_ASSETS = ${JSON.stringify(compressed)} as const satisfies readonly StarterAsset[];\n`;
}
export async function guideTemplateSource(){
  const text=await readFile(new URL('examples/Magical_Cards示例及用法说明.md',project),'utf8');
  return '// Generated by scripts/build-starter-assets.mjs from the guide template.\n'+`export const GUIDE_TEMPLATE = ${JSON.stringify(text)};\n`;
}
if(process.argv[1]===fileURLToPath(import.meta.url)){
  const [assets,guide]=await Promise.all([starterAssetSource(),guideTemplateSource()]);
  for(const [file,source]of [['src/starter-assets.ts',assets],['src/onboarding-template.ts',guide]]){
    const path=new URL(file,project);
    if(process.argv.includes('--check')){
      if(await readFile(path,'utf8')!==source)throw new Error(`Generated ${file} differs from its source. Run npm run assets:build.`);
    }else await writeFile(path,source);
  }
  process.stdout.write(process.argv.includes('--check')?'Compressed starter assets and guide template match their sources.\n':`Compressed starter assets: ${Buffer.byteLength(assets)} bytes; guide template generated.\n`);
}
